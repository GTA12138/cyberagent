// Package apicontract derives browser DTOs from the Go JSON representation.
package apicontract

import (
	"encoding/json"
	"fmt"
	"chengjian.local/chengjian/db"
	"reflect"
	"strings"
)

func Types() string {
	var out strings.Builder
	out.WriteString("// Code generated by go run ./cmd/api-types; DO NOT EDIT.\n")
	t := reflect.TypeOf(db.ExecutionAttempt{})
	fmt.Fprintf(&out, "export interface %s {\n", t.Name())
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		tag := strings.Split(f.Tag.Get("json"), ",")[0]
		if tag == "-" {
			continue
		}
		if tag == "" {
			tag = f.Name
		}
		var kind string
		switch f.Type.Kind() {
		case reflect.String:
			kind = "string"
		case reflect.Int, reflect.Int64, reflect.Float64:
			kind = "number"
		case reflect.Bool:
			kind = "boolean"
		default:
			panic(fmt.Sprintf("unsupported contract field %s: %s", f.Name, f.Type))
		}
		fmt.Fprintf(&out, "  %s: %s;\n", tag, kind)
	}
	out.WriteString("}\n")
	return out.String()
}
